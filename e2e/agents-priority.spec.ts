import {mkdirSync} from 'node:fs';
import {test,expect,login,seedRealtimeAgent,openAgentAction} from './auth-fixture';

for(const width of [390,1366]) for(const theme of ["light","dark"]) test(`Agents priority layout and inline icon controls ${width} ${theme}`,async({page,server},testInfo)=>{
  await page.setViewportSize({width,height:844});seedRealtimeAgent(server);await login(page,server);
  await page.getByLabel('Appearance').selectOption(theme);
  await expect(page.getByText('Not default',{exact:true})).toHaveCount(0);
  const add=page.getByRole('button',{name:'+ Add Agent',exact:true});
  expect(await page.locator('.page-heading').evaluate(el=>getComputedStyle(el).borderBottomWidth)).toBe('1px');
  expect(await page.locator('.agents-toolbar').evaluate(el=>getComputedStyle(el).borderBottomWidth)).toBe('0px');
  const heading=(await page.locator('.page-heading').boundingBox())!, addBox=(await add.boundingBox())!;
  await expect(page.locator('.page-heading').getByRole('button',{name:'+ Add Agent',exact:true})).toBeVisible();
  expect(addBox.y+addBox.height).toBeLessThan(heading.y+heading.height);
  const titleBox=(await page.getByRole('heading',{name:'Agents',exact:true,level:1}).boundingBox())!;
  expect(Math.abs(titleBox.y+titleBox.height/2-addBox.y-addBox.height/2)).toBeLessThan(1);
  expect(addBox.x).toBeGreaterThan(titleBox.x+titleBox.width);
  console.log(JSON.stringify({width,theme,titleBox,addBox,dividerY:heading.y+heading.height}));
  await page.screenshot({path:testInfo.outputPath(`header-${width}-${theme}.png`)});
  const agentId=await page.locator('.agent-list>li').filter({has:page.getByRole('heading',{name:'Vauxr Support',level:3,exact:true})}).getAttribute('data-agent-id');
  const row=page.locator(`main li[data-agent-id="${agentId}"]`);
  const setDefault=row.getByRole('button',{name:'Set as default',exact:true});
  await expect(setDefault).toBeVisible();
  expect(await setDefault.evaluate(el=>{const s=getComputedStyle(el);return {background:s.backgroundColor,border:s.borderTopColor,shadow:s.boxShadow};})).toEqual({background:'rgba(0, 0, 0, 0)',border:'rgba(0, 0, 0, 0)',shadow:'none'});
  const name=row.getByRole('heading',{name:'Vauxr Support',exact:true});
  const original=await name.evaluate(el=>({x:el.getBoundingClientRect().x,font:getComputedStyle(el).fontSize,weight:getComputedStyle(el).fontWeight}));
  const pencil=row.getByRole('button',{name:'Edit agent name',exact:true});
  expect(await pencil.evaluate(el=>{const c=getComputedStyle(el).color.match(/[\d.]+/g)!.map(Number);return c[2]>c[0]&&c[2]>c[1];})).toBe(true);
  await pencil.click();const input=row.getByLabel('Agent name',{exact:true});
  expect(await input.evaluate(el=>({x:el.getBoundingClientRect().x,font:getComputedStyle(el).fontSize,weight:getComputedStyle(el).fontWeight}))).toEqual(original);
  for(const label of ['Save name','Cancel name edit']){
    const button=row.getByRole('button',{name:label,exact:true});
    await expect(button).toHaveText('');await expect(button.locator('svg')).toHaveCount(1);
    const b=(await button.boundingBox())!, f=(await input.boundingBox())!;
    expect(b.x).toBeGreaterThanOrEqual(f.x);expect(b.x+b.width).toBeLessThanOrEqual(f.x+f.width+1);
    expect(b.y).toBe(f.y);expect(b.height).toBe(f.height);
  }
  const artifacts=testInfo.outputPath('screenshots');mkdirSync(artifacts,{recursive:true});
  await page.screenshot({path:`${artifacts}/inline-${width}-${theme}.png`});
  await expect(input).toHaveAttribute('maxlength','200');
  const editBox=(await input.boundingBox())!; expect(editBox.x+editBox.width).toBeLessThanOrEqual(width);
  if(width===1366) expect(editBox.width).toBeGreaterThan(350);
  await input.fill('Cancelled name');await row.getByRole('button',{name:'Cancel name edit',exact:true}).click();
  await expect(name).toBeVisible();
  await pencil.click();await input.fill('P'.repeat(200));await input.press('Enter');
  await expect(page.getByRole('heading',{name:'P'.repeat(200),exact:true})).toBeVisible();
  await page.reload(); await expect(page.getByRole('heading',{name:'P'.repeat(200),exact:true})).toBeVisible();
  await openAgentAction(page,'Voice pipeline for '+'P'.repeat(200));
  const modal=page.getByRole('dialog',{name:'Voice pipeline',exact:true});await expect(modal).toBeVisible();
  await expect(modal.getByText('MAKE IT YOURS',{exact:true})).toHaveCount(0);
  expect(await modal.getByRole('heading',{name:'Voice pipeline',exact:true}).evaluate(el=>parseFloat(getComputedStyle(el).fontSize))).toBeLessThanOrEqual(24);
  const close=modal.getByRole('button',{name:'Close dialog',exact:true});
  const b=(await close.boundingBox())!, svg=(await close.locator('svg').boundingBox())!;
  expect(Math.abs(b.x+b.width/2-svg.x-svg.width/2)).toBeLessThan(1);
  expect(Math.abs(b.y+b.height/2-svg.y-svg.height/2)).toBeLessThan(1);
  await modal.evaluate(el=>Promise.all(el.getAnimations().map(animation=>animation.finished.catch(()=>{}))));
  const endpoint=modal.getByRole('button',{name:'Edit '+'P'.repeat(200),exact:true});
  await expect(endpoint).toHaveAttribute('title','P'.repeat(200));
  const labelBox=(await endpoint.boundingBox())!, graphBox=(await modal.locator('.pipeline-graph').boundingBox())!;
  const saveBox=(await modal.getByRole('button',{name:'Save pipeline configuration',exact:true}).boundingBox())!;
  expect(labelBox.y).toBeGreaterThanOrEqual(graphBox.y);
  expect(labelBox.y+labelBox.height).toBeLessThanOrEqual(graphBox.y+graphBox.height);
  expect(labelBox.y+labelBox.height).toBeLessThan(saveBox.y);
  expect(labelBox.height).toBeLessThanOrEqual(48);
  await expect(modal.locator('.modal-body > h3')).toHaveAttribute('title','P'.repeat(200));
  await page.screenshot({path:`${artifacts}/voice-modal-${width}-${theme}.png`});
  await close.click();await add.click();
  await expect(page.getByRole('dialog',{name:'Add Agent',exact:true}).getByText('MAKE IT YOURS',{exact:true})).toHaveCount(0);
});
