import { test, expect, login } from "./auth-fixture";
for (const width of [390,1366]) test(`standalone LangGraph setup, modes and removal at ${width}`, async ({page,server})=>{
  await page.setViewportSize({width,height:900});
  await page.addInitScript(()=>{(window as any).micCalls=0;navigator.mediaDevices.getUserMedia=async()=>{(window as any).micCalls++;throw Error("Mic off");};});
  await login(page,server);
  console.log(`LangGraph ${width}: authenticated`);
  const create=page.getByRole("region",{name:"Add local agent",exact:true});
  await create.getByLabel("Local agent name").fill("Household graph");
  await create.getByRole("button",{name:"Add LangGraph agent",exact:true}).click();
  const detail=page.getByRole("region",{name:"Agent detail",exact:true});
  await expect(detail.getByRole("heading",{name:"Household graph",exact:true})).toBeVisible();
  await expect(detail.getByRole("region",{name:"Agent model runtime",exact:true})).toContainText("Setup needed");
  await expect(detail.getByLabel("Enable Live",{exact:true})).toBeDisabled();
  console.log(`LangGraph ${width}: Standard enabled, Live unavailable`);
  await page.getByRole("button",{name:"Connect browser",exact:true}).click();
  console.log(`LangGraph ${width}: browser connected`);
  const companion=page.locator("#voice-companion");
  await companion.getByLabel("Conversation agent",{exact:true}).selectOption({label:"Household graph"});
  console.log(`LangGraph ${width}: agent selected`);
  await companion.getByLabel("Text message",{exact:true}).fill("Help with the household");
  await companion.getByRole("button",{name:"Send text",exact:true}).click();
  console.log(`LangGraph ${width}: text sent`);
  await expect(companion.getByLabel("Agent text response",{exact:true})).toContainText("LangGraph agent needs setup");
  await companion.getByRole("button",{name:"Collapse voice companion",exact:true}).click();
  await detail.getByRole("button",{name:"Remove local agent",exact:true}).click();
  await expect(page.getByRole("alert")).toContainText("unassign all devices");
  await companion.getByRole("button",{name:"Expand voice companion",exact:true}).click();
  await companion.getByLabel("Conversation agent",{exact:true}).selectOption("vauxr-support");
  await companion.getByRole("button",{name:"Collapse voice companion",exact:true}).click();
  await detail.getByRole("button",{name:"Remove local agent",exact:true}).click();
  await expect(page.getByRole("button",{name:"View agent Household graph",exact:true})).toHaveCount(0);
  console.log(`LangGraph ${width}: setup-needed text and guarded removal verified`);
  expect(await page.evaluate(()=>(window as any).micCalls)).toBe(0);
  await page.screenshot({timeout:10000, animations:"disabled",path:`/tmp/vauxr-langgraph-${width}.png`,fullPage:true});
});
