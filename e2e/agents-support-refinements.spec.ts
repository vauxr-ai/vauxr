import {readFileSync,writeFileSync} from "node:fs";
import {test,expect,login} from './auth-fixture';
for(const width of [390,1366]) test(`Support avatar and deletion persist ${width}`,async({page,server})=>{
 await page.setViewportSize({width,height:844});await login(page,server);
 let dialogs=0;page.on('dialog',async d=>{dialogs++;await d.dismiss();});
 await page.getByRole('button',{name:'+ Add Agent',exact:true}).click();
 const add=page.getByRole('dialog',{name:'Add Agent',exact:true});
 await add.getByRole('button',{name:'Choose Vauxr Support',exact:true}).click();
 await add.getByLabel('Agent name',{exact:true}).fill('Added Support');
 await add.getByRole('button',{name:'Create agent',exact:true}).click();
 const row=page.locator('.agent-list>li').filter({has:page.getByRole('heading',{name:'Added Support',exact:true})});
 await expect(row).toBeVisible();
 await expect(row.locator(".agent-avatar img")).toBeVisible();
 expect(await row.locator(".agent-avatar img").evaluate((el: HTMLImageElement)=>el.complete && el.naturalWidth>0)).toBe(true);
 const id=await row.getAttribute('data-agent-id');
 const icon=await page.request.get(server.origin+'/agent-types/vauxr-support.png');
 const avatar=await page.request.get(server.origin+`/api/agents/${id}/avatar`);
 expect(avatar.status()).toBe(200);expect(await avatar.body()).toEqual(await icon.body());
 await server.restart();await page.reload();await expect(row).toBeVisible();
 await expect(row.locator(".agent-avatar img")).toBeVisible();
 const persisted=await page.request.get(server.origin+`/api/agents/${id}/avatar`);expect(await persisted.body()).toEqual(await icon.body());
 await row.locator('details.agent-actions summary').click();await row.getByRole('button',{name:'Delete agent',exact:true}).click();
 const confirmation=page.getByRole('dialog',{name:'Delete agent',exact:true});
 await expect(confirmation).toBeVisible();await confirmation.getByRole('button',{name:'Cancel',exact:true}).click();await expect(row).toBeVisible();
 await row.locator('details.agent-actions summary').click();await row.getByRole('button',{name:'Delete agent',exact:true}).click();await confirmation.getByRole('button',{name:'Delete agent',exact:true}).click();
 await expect(row).toHaveCount(0);await server.restart();await page.reload();await expect(row).toHaveCount(0);expect(dialogs).toBe(0);
});

for (const width of [390, 1366]) test(`Default Support wire identity and header action ${width}`, async ({page,server}) => {
 await page.setViewportSize({width,height:844}); await login(page,server);
 // Disposable persisted configuration mirrors the bundled OpenClaw route on Nova.
 const path = server.data+'/agents.json';
 const inventory = JSON.parse(readFileSync(path,'utf8'));
 inventory.agents.push({id:'bundled-openclaw',name:'OpenClaw',type:'openclaw',builtin:true,createdAt:new Date(0).toISOString()});
 inventory.active_agent = 'bundled-openclaw';
 writeFileSync(path,JSON.stringify(inventory));
 await server.restart(); await page.reload();
 const agents = await (await page.request.get(server.origin+'/api/agents')).json();
 const support = agents.find((a: any) => a.definition_id === 'vauxr-support' && a.builtin);
 const protectedAgent = agents.find((a: any) => a.builtin && a.definition_id !== 'vauxr-support');
 expect(support).toBeTruthy(); expect(protectedAgent).toBeTruthy(); expect(support.active).toBe(false);
 const header = page.locator('.page-heading');
 await expect(header.getByRole('button',{name:'+ Add Agent',exact:true})).toBeVisible();
 expect(await header.evaluate(el => getComputedStyle(el).borderBottomStyle)).not.toBe('none');
 const protectedRow = page.locator(`[data-agent-id="${protectedAgent.id}"]`);
 await protectedRow.locator('details.agent-actions summary').click();
 await expect(protectedRow.getByRole('button',{name:'Delete agent',exact:true})).toBeDisabled();
 const row = page.locator(`[data-agent-id="${support.id}"]`);
 await expect(row.locator(".agent-avatar img")).toBeVisible();
 await row.locator('details.agent-actions summary').click();
 await expect(row.getByRole('button',{name:'Delete agent',exact:true})).toBeEnabled();
 await row.getByRole('button',{name:'Delete agent',exact:true}).click();
 await page.getByRole('dialog',{name:'Delete agent',exact:true}).getByRole('button',{name:'Delete agent',exact:true}).click();
 await expect(row).toHaveCount(0); await server.restart(); await page.reload(); await expect(row).toHaveCount(0);
});
