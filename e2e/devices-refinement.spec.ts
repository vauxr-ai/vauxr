import { mkdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { resolve } from "node:path";
import { test, expect, login } from "./auth-fixture";

for (const width of [390,1366]) for (const theme of ["light","dark"]) {
  test(`device editor autosave, diagnostics and real usage API at ${width}px ${theme}`, async ({page,server}) => {
    test.setTimeout(90000);
    await page.setViewportSize({width,height:900});
    await login(page,server);
    await page.getByLabel("Appearance").selectOption(theme);
    await page.getByRole("button",{name:"Connect browser",exact:true}).click();
    await expect(page.locator("#voice-companion").getByLabel("Conversation agent")).toBeEnabled();
    await page.getByRole("button", {name:"Collapse voice companion",exact:true}).click();
    await page.getByRole("button",{name:"Devices",exact:true}).click();
    const card=page.locator("main li").first();
    await card.getByRole("button").first().click({timeout:10000});
    await expect(card.getByRole("combobox",{name:"Assigned agent"})).toBeVisible();
    await expect(card.getByRole("combobox",{name:"Assigned agent"})).toContainText("Use default agent");
    await expect(card.getByRole("combobox",{name:"STT backend"})).toHaveCount(0);
    await card.getByRole("button",{name:"Edit device name"}).click();
    await card.getByRole("textbox",{name:"Device name"}).fill("Studio Speaker");
    await card.getByRole("textbox",{name:"Device name"}).press("Enter");
    await expect(card.getByRole("heading",{name:/^Studio Speaker/})).toBeVisible();
    await card.getByRole("button",{name:"Always",exact:true}).click();
    await expect(card.getByRole("button",{name:"Always",exact:true})).toHaveAttribute("aria-pressed","true");
    await card.getByRole("button",{name:"Override agent voice pipeline defaults"}).click();
    await expect(card.getByRole("combobox",{name:"Voice transport"})).toBeVisible();
    await expect(card.getByRole("combobox",{name:"STT backend"})).toBeVisible();
    const graph = card.getByRole("group", {name:"Standard voice pipeline",exact:true});
    const graphBox = await graph.boundingBox();
    const overrideBox = await card.locator(".device-voice-overrides").boundingBox();
    expect(graphBox!.width).toBeGreaterThan(overrideBox!.width * 0.95);
    await expect(card.getByRole("textbox",{name:"Announcement message"})).toHaveValue("Hello world! this is the vauxr speaker test announcement. I sure hope you can hear me");
    const artifacts="/tmp/vauxr-devices-refinement-screenshots";
    mkdirSync(artifacts,{recursive:true});
    await card.scrollIntoViewIfNeeded();
    await page.screenshot({path:resolve(artifacts,`devices-${width}-${theme}.png`)});
    await card.getByRole("button",{name:"Device Diagnostics"}).click();
    const dialog=page.getByRole("dialog",{name:"Device Diagnostics"});
    expect(await dialog.evaluate(el=>el.matches(":modal"))).toBe(true);
    for (const name of ["Set volume","Mute","Unmute","Reboot device","Install firmware","Set barge-in"]) await expect(dialog.getByRole("button",{name,exact:true})).toBeVisible();
    await dialog.getByRole("spinbutton",{name:"Volume",exact:true}).fill("37");
    const response=page.waitForResponse(r=>r.url().endsWith("/command") && r.request().method()==="POST");
    await dialog.getByRole("button",{name:"Set volume",exact:true}).click();
    const sent=await response; expect(sent.status()).toBe(200); expect(sent.request().postDataJSON()).toEqual({command:"set_volume",params:{volume:37}});
    await page.screenshot({path:resolve(artifacts,`diagnostics-${width}-${theme}.png`)});
    for(let n=0;n<14;n++){ await page.keyboard.press("Tab"); expect(await dialog.evaluate(el=>el.contains(document.activeElement))).toBe(true); }
    await page.keyboard.press("Escape");
    await expect(dialog).toHaveCount(0);
    await expect(card.getByRole("button",{name:"Device Diagnostics"})).toBeFocused();
    const devices=await (await page.request.get(server.origin+"/api/devices")).json();
    const device=devices.find((d:any)=>d.config.name==="Studio Speaker");
    expect(device.config.follow_up_mode).toBe("always");
    execFileSync("python3",["-c", "import sys; from pathlib import Path; from vauxr.devices.metrics import MetricsStore; s=MetricsStore(Path(sys.argv[1])); s.record(sys.argv[2], 'stt_transcriptions'); s.record(sys.argv[2], 'tts_syntheses')",server.data,device.id],{env:{PATH:process.env.PATH,PYTHONPATH:resolve(import.meta.dirname,"../src")}});
    await card.getByRole("button",{name:"Refresh device metrics"}).click();
    await expect(card.getByRole("img",{name:/STT transcriptions: 1 across/})).toBeVisible();
    await card.getByRole("combobox",{name:"Time frame"}).selectOption("7d");
    await expect(card.getByRole("img",{name:/TTS syntheses: 1 across 28 buckets/})).toBeVisible();
    await card.getByRole("region",{name:"Device metrics & logging"}).scrollIntoViewIfNeeded();
    await page.screenshot({path:resolve(artifacts,`metrics-${width}-${theme}.png`)});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.reload();
    await page.getByRole("button",{name:"Connect browser",exact:true}).click();
    await expect(page.locator("#voice-companion").getByLabel("Conversation agent")).toBeEnabled();
    await page.getByRole("button", {name:"Collapse voice companion",exact:true}).click();
    await page.getByRole("button",{name:"Devices",exact:true}).click();
    await page.locator("main li").first().getByRole("button").first().click({timeout:10000});
    await expect(page.getByRole("button",{name:"Always",exact:true})).toHaveAttribute("aria-pressed","true");
    await expect(page.getByRole("heading",{name:/^Studio Speaker/})).toBeVisible();
    await expect(page.getByRole("img",{name:/STT transcriptions: 1 across/})).toBeVisible();
  });
}
